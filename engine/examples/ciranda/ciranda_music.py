import sys,os,json;sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..'))
from qp_music import *
D=json.load(open(sys.argv[1]))['TL'];T=D['T'];EV=D['EV']
pad(0,T['FAST'],0.08)
jingle(0,T['SPIN'],bpm=104,semi=0,g=0.5,full=False)
jingle(T['SPIN'],T['FAST'],bpm=104,semi=0,g=0.7)
jingle(T['FAST'],T['STOP'],bpm=150,semi=2,g=0.75,claps=True)
jingle(T['STOP'],T['OPEN'],bpm=90,semi=-2,g=0.45,full=False)
jingle(T['OPEN'],T['FIVE'],bpm=112,semi=3,g=0.65)
jingle(T['FIVE'],T['SIT'],bpm=104,semi=5,g=0.7,claps=True)
jingle(T['SIT'],T['YAY'],bpm=104,semi=0,g=0.5,full=False)
for t,ty in EV:
  if ty=='bark':bark(t,0.3);bark(t+0.25,0.25)
  if ty=='ta':fanfare(t,0.2)
  if ty=='go':whistle(t,0.4,0.22)
  if ty=='run':whoosh(t,0.6,0.25)
  if ty=='whoosh':slide(t,700,250,0.8,0.15)
  if ty=='boing':boing(t,0.2)
  if ty=='thud':thud(t,0.35)
  if ty=='laugh':giggle(t,0.13,8)
  if ty=='chime':arp(t,76,0.25)
  if ty=='up':slide(t,300,800,1.2,0.12)
  if ty=='down':slide(t,800,300,1.2,0.12)
  if ty=='confetti':fanfare(t,0.32);add(t,clap(),1.0)
jingle(T['YAY']+0.4,T['END'],bpm=110,semi=2,g=1.0,claps=True)
e=T['END']-1.6
add(e,bell(62,1.5),0.3);add(e,bell(66,1.5),0.25);add(e,bell(69,1.5),0.25);add(e,bell(74,1.5),0.3)
save(sys.argv[2])
